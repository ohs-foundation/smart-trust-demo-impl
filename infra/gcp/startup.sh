#!/bin/bash
set -euo pipefail

if ! command -v docker >/dev/null; then
  apt-get update
  apt-get install -y ca-certificates curl gnupg nginx certbot python3-certbot-nginx gettext-base openssl
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  echo "deb [arch=amd64 signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi

gcloud auth configure-docker ${registry} --quiet
